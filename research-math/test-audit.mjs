import fs from 'node:fs/promises';
import {createRequire} from 'node:module';
import {pathToFileURL} from 'node:url';
const require=createRequire(process.env.CODEX_PRIMARY_RUNTIME_NODE_MODULES+'/entry.js');
const canvas=require('@napi-rs/canvas');
for(const key of ['DOMMatrix','ImageData','Path2D'])globalThis[key]=canvas[key];
if(!Uint8Array.prototype.toHex)Uint8Array.prototype.toHex=function(){return Buffer.from(this).toString('hex')};
if(!Map.prototype.getOrInsertComputed)Map.prototype.getOrInsertComputed=function(k,f){if(!this.has(k))this.set(k,f(k));return this.get(k)};
if(!Map.prototype.getOrInsert)Map.prototype.getOrInsert=function(k,v){if(!this.has(k))this.set(k,v);return this.get(k)};
if(!Math.sumPrecise)Math.sumPrecise=vs=>[...vs].reduce((a,b)=>a+b,0);
const release=process.cwd()+'/cp19/work/app';
const pdfjs=await import(pathToFileURL(release+'/vendor/pdfjs/pdf.min.mjs'));
pdfjs.GlobalWorkerOptions.workerSrc=pathToFileURL(release+'/vendor/pdfjs/pdf.worker.min.mjs').href;
const pdf=await pdfjs.getDocument({data:new Uint8Array(await fs.readFile('cp19/audit/evidence/pdf_math/mathematics_fixture.pdf')),isEvalSupported:false,useSystemFonts:false,disableFontFace:false,stopAtErrors:true,enableXfa:false,standardFontDataUrl:release+'/vendor/pdfjs/standard_fonts/',cMapUrl:release+'/vendor/pdfjs/cmaps/',cMapPacked:true,wasmUrl:release+'/vendor/pdfjs/wasm/'}).promise;
const page=await pdf.getPage(1), viewport=page.getViewport({scale:1});
const {normalizeItems}=await import(pathToFileURL(release+'/app/pdf-reader.js'));
const {reconstructMath,extractMathVectors}=await import('./math-geometry.js');
const items=normalizeItems(await page.getTextContent(),viewport,pdfjs);
const vectors=extractMathVectors(await page.getOperatorList(),viewport,pdfjs.OPS);
const result=reconstructMath(items,vectors,{pageNumber:1});
await fs.writeFile('cp19/research-math/audit-result.json',JSON.stringify({items,vectors,result},null,2));
console.log(JSON.stringify(result.regions,null,2));
