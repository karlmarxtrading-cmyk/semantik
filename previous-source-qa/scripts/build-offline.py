"""Build a revision-bound offline asset manifest and lazy service worker."""
from pathlib import Path
import hashlib,json

ROOT=Path(__file__).resolve().parents[1]
paths=[ROOT/'index.html',ROOT/'icon.svg',ROOT/'manifest.webmanifest']
for directory in ['app','assets','runtime','vendor']:
    paths.extend(p for p in (ROOT/directory).rglob('*') if p.is_file())
entries=[]
for p in sorted(paths):
    data=p.read_bytes()
    entries.append({'path':'/'+p.relative_to(ROOT).as_posix(),'size':len(data),'sha256':hashlib.sha256(data).hexdigest()})
fingerprint=hashlib.sha256(json.dumps(entries,sort_keys=True).encode()).hexdigest()[:12]
cache='semantik-pdf-cp17-'+fingerprint
(ROOT/'offline-assets.json').write_text(json.dumps({'version':'CP17','cache':cache,'files':entries},indent=2)+'\n')
shell=['/','/index.html','/app/styles.css','/app/main.js','/app/storage.js','/icon.svg','/manifest.webmanifest','/offline-assets.json']
source='''/* Generated by scripts/build-offline.py. Heavy assets are cached on demand. */
const CACHE=__CACHE__;
const SHELL=__SHELL__;
const ALLOWED=new Set(__ALLOWED__);
self.addEventListener('install',event=>{
  event.waitUntil(caches.open(CACHE).then(cache=>cache.addAll(SHELL)));
  // An active document keeps its current app; update activates after old tabs close.
});
self.addEventListener('activate',event=>{
  event.waitUntil((async()=>{
    const keys=await caches.keys();
    for(const key of keys)if((key.startsWith('semantik-pdf-cp17-')||key.startsWith('semantik-shell-'))&&key!==CACHE)await caches.delete(key);
    await self.clients.claim();
  })());
});
self.addEventListener('fetch',event=>{
  const request=event.request,url=new URL(request.url);
  const rootNavigation=request.mode==='navigate'&&(url.pathname==='/'||url.pathname==='/index.html');
  if(request.method!=='GET'||url.origin!==self.location.origin||url.pathname.startsWith('/models/'))return;
  if(url.search&&!rootNavigation)return;
  if(!ALLOWED.has(url.pathname)&&!SHELL.includes(url.pathname))return;
  event.respondWith((async()=>{
    const cache=await caches.open(CACHE);
    const key=rootNavigation?'/index.html':request;
    try{
      const response=await fetch(request);
      if(response.ok){try{await cache.put(key,response.clone());}catch{ /* Low storage must not break online reading. */ }return response;}
      const stored=await cache.match(key);return stored||response;
    }catch(error){
      const stored=await cache.match(key);
      if(stored)return stored;
      if(request.mode==='navigate'&&(url.pathname==='/'||url.pathname==='/index.html')){
        const index=await cache.match('/index.html');if(index)return index;
      }
      return new Response('Komponen belum tersedia offline. Hubungkan internet dan siapkan offline terlebih dahulu.',{status:503,headers:{'Content-Type':'text/plain; charset=utf-8'}});
    }
  })());
});
'''.replace('__CACHE__',json.dumps(cache)).replace('__SHELL__',json.dumps(shell)).replace('__ALLOWED__',json.dumps([x['path'] for x in entries]))
(ROOT/'sw.js').write_text(source)
print(json.dumps({'cache':cache,'shell_files':len(shell),'offline_files':len(entries),'offline_bytes':sum(x['size'] for x in entries)}))
